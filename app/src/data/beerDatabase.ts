// SEARCH & HELPERS
// ============================================

export function searchBeers(query: string): Beer[] {
  const lowerQuery = query.toLowerCase();
  return BEER_DATABASE.filter(beer =>
    beer.name.toLowerCase().includes(lowerQuery) ||
    beer.brewery.toLowerCase().includes(lowerQuery) ||
    beer.style.toLowerCase().includes(lowerQuery) ||
    beer.flavorNotes.some(note => note.toLowerCase().includes(lowerQuery))
  ).slice(0, 20);
}

export function getBeersByStyle(styleId: string): Beer[] {
  return BEER_DATABASE.filter(beer => beer.styleId === styleId);
}

export function getTopRatedBeers(limit: number = 10): Beer[] {
  return [...BEER_DATABASE]
    .sort((a, b) => b.rating - a.rating)
    .slice(0, limit);
}

export function getBeersByFoodPairing(food: string): Beer[] {
  const lowerFood = food.toLowerCase();
  return BEER_DATABASE.filter(beer =>
    beer.pairings.some(pairing => pairing.toLowerCase().includes(lowerFood))
  );
}

export function getBeersForOccasion(occasion: string): Beer[] {
  const occasionMap: Record<string, string[]> = {
    'bbq': ['ipa', 'pale-ale', 'amber', 'pilsner'],
    'date night': ['tripel', 'dubbel', 'saison', 'witbier'],
    'game day': ['pilsner', 'pale-ale', 'ipa', 'amber'],
    'thanksgiving': ['marzen', 'brown', 'porter', 'saison'],
    'christmas': ['imperial-stout', 'quad', 'doppelbock', 'barleywine'],
    'summer': ['pilsner', 'helles', 'witbier', 'gose', 'berliner'],
    'winter': ['imperial-stout', 'porter', 'doppelbock', 'quad'],
  };
  
  const styles = occasionMap[occasion.toLowerCase()] || [];
  return BEER_DATABASE.filter(beer => styles.includes(beer.styleId));
}
